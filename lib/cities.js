/** Fuzzy-ish prefix search, ranked: exact > prefix > contains. */
export function searchCities(query, limit = 8) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const scored = [];
  for (const c of CITIES) {
    const n = c.name.toLowerCase();
    const r = c.region.toLowerCase();
    let score = -1;
    if (n === q) score = 0;
    else if (n.startsWith(q)) score = 1;
    else if (n.includes(q)) score = 2;
    else if (r.startsWith(q)) score = 3;
    else if (r.includes(q)) score = 4;
    if (score >= 0) scored.push({ c, score });
  }
  scored.sort((a, b) => a.score - b.score || a.c.name.length - b.c.name.length);
  return scored.slice(0, limit).map((s) => s.c);
}

export const DEFAULT_CITY = CITIES.find((c) => c.name === "Delhi");

export default CITIES;
